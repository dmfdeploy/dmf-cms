_LABELS = {"namespace": "dmf-cms", "job": "dmf-cms/dmf-cms"}


def test_retention_not_enforced_when_compactor_disabled():
    config = """
compactor:
  retention_enabled: false
limits_config:
  retention_period: 168h
"""
    window = audit_events.resolve_retention_window(config, _LABELS)
    assert window.known is False
    assert window.reason == "not-enforced"


def test_retention_falls_back_to_global_when_no_stream_selector_matches():
    # This is condition 1's exact case: the queried job label matches
    # neither the k3s-audit nor the security-job stream rule, so today the
    # global is correct -- but the code must evaluate that, not assume it.
    config = """
compactor:
  retention_enabled: true
limits_config:
  retention_period: 168h
  retention_stream:
    - selector: '{job="k3s-audit"}'
      period: 720h
      priority: 2
    - selector: '{job=~".+-security"}'
      period: 720h
      priority: 1
"""
    window = audit_events.resolve_retention_window(config, _LABELS)
    assert window.known is True
    assert window.seconds == 168 * 3600
    assert window.reason == ""


def test_retention_uses_matching_stream_selector_over_global():
    config = """
compactor:
  retention_enabled: true
limits_config:
  retention_period: 168h
  retention_stream:
    - selector: '{job="dmf-cms/dmf-cms"}'
      period: 720h
      priority: 1
"""
    window = audit_events.resolve_retention_window(config, _LABELS)
    assert window.known is True
    assert window.seconds == 720 * 3600


def test_retention_stream_priority_breaks_a_tie_between_two_matching_rules():
    config = """
compactor:
  retention_enabled: true
limits_config:
  retention_period: 168h
  retention_stream:
    - selector: '{job=~"dmf-cms.*"}'
      period: 240h
      priority: 1
    - selector: '{job="dmf-cms/dmf-cms"}'
      period: 480h
      priority: 5
"""
    window = audit_events.resolve_retention_window(config, _LABELS)
    assert window.seconds == 480 * 3600


def test_retention_unavailable_on_unparseable_yaml():
    window = audit_events.resolve_retention_window("not: valid: yaml: [", _LABELS)
    assert window.known is False
    assert window.reason == "unparseable"


def test_retention_unparseable_on_garbage_duration():
    config = """
compactor:
  retention_enabled: true
limits_config:
  retention_period: not-a-duration
"""
    window = audit_events.resolve_retention_window(config, _LABELS)
    assert window.known is False
    assert window.reason == "unparseable"


def test_retention_unparseable_when_limits_config_missing():
    config = "compactor:\n  retention_enabled: true\n"
    window = audit_events.resolve_retention_window(config, _LABELS)
    assert window.known is False
    assert window.reason == "unparseable"


def test_retention_a_broken_regex_selector_never_matches_and_never_crashes():
    config = """
compactor:
  retention_enabled: true
limits_config:
  retention_period: 168h
  retention_stream:
    - selector: '{job=~"("}'
      period: 720h
      priority: 9
"""
    window = audit_events.resolve_retention_window(config, _LABELS)
    assert window.known is True
    assert window.seconds == 168 * 3600  # falls back to global, does not crash


# ----------------------------------------------------------------------
# classify_record / user_passes_gate — the closed membership table
# ----------------------------------------------------------------------

def test_classify_covered_classes():
    assert audit_events.classify_record("deploy", "alice") == "deploy"
    assert audit_events.classify_record("teardown", "alice") == "teardown"
    assert audit_events.classify_record("switch-source", "bob") == "switch-source"


def test_classify_splits_rollback_by_actor():
    assert audit_events.classify_record("rollback", "system:auto-rollback") == "auto-rollback"
    assert audit_events.classify_record("rollback", "alice") == "rollback"


def test_classify_excluded_classes_are_named_not_dropped_from_the_table():
    for action in ("finalise-purge", "launch", "verify-drain"):
        cls = audit_events.classify_record(action, "alice")
        assert cls == action
        assert audit_events._CLASS_INFO[cls]["status"] != audit_events.COVERED


def test_classify_unrecognised_action_fails_closed():
    assert audit_events.classify_record("mystery-action", "alice") is None


def test_gate_operator_role_passes_operator_classes_not_media_workloads():
    assert audit_events.user_passes_gate("deploy", role="operator", groups=()) is True
    assert audit_events.user_passes_gate("teardown", role="operator", groups=()) is True
    assert audit_events.user_passes_gate("auto-rollback", role="operator", groups=()) is True
    assert audit_events.user_passes_gate("switch-source", role="operator", groups=()) is False


def test_gate_viewer_in_media_engineers_passes_only_switch_source():
    groups = ("dmf-console-viewer", "media-engineers")
    assert audit_events.user_passes_gate("switch-source", role="viewer", groups=groups) is True
    assert audit_events.user_passes_gate("deploy", role="viewer", groups=groups) is False


def test_gate_excluded_classes_pass_for_nobody():
    for cls in ("finalise-purge", "launch", "verify-drain", "rollback"):
        assert audit_events.user_passes_gate(cls, role="admin", groups=("media-engineers",)) is False


