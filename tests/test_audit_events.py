def test_watched_action_acceptance_outcome_is_in_flight():
    for action, outcome in (("deploy", "dispatched"), ("teardown", "launched"), ("rollback", "auto-triggered")):
        result = audit_events.build_outcome(action, outcome)
        assert result == {"state": "in_flight", "detail": outcome}


def test_switch_source_active_is_a_real_succeeded_verdict():
    result = audit_events.build_outcome("switch-source", "active")
    assert result == {"state": "succeeded", "detail": "active"}


def test_switch_source_non_active_is_failed_with_generic_default_copy():
    result = audit_events.build_outcome("switch-source", "failed_rollback_required")
    assert result["state"] == "failed"
    assert result["detail"] == "failed_rollback_required"  # raw preserved, expert-only
    assert "failed_rollback_required" not in result["headline"]
    assert "failed_rollback_required" not in result["meaning"]


def test_refusal_token_overrides_watched_acceptance_and_gets_plain_language_copy():
    result = audit_events.build_outcome("deploy", "facility-busy")
    assert result["state"] == "failed"
    assert result["headline"] == "Another operation is already using this facility"
    assert result["detail"] == "facility-busy"  # raw string carried, never in headline/meaning/next_step
    for key in ("headline", "meaning", "next_step"):
        assert "facility-busy" not in result[key]


def test_awx_error_prefix_gets_generic_copy_and_keeps_raw_as_detail_only():
    result = audit_events.build_outcome("teardown", "awx-error:503")
    assert result["state"] == "failed"
    assert result["detail"] == "awx-error:503"
    for key in ("headline", "meaning", "next_step"):
        assert "awx-error:503" not in result[key]


def test_unrecognised_refusal_token_still_gets_honest_generic_copy_never_raw():
    # _describe_failure directly: the plan's refusal vocabulary (§4.4) is a
    # closed set, same principle as the class table — a token outside it
    # must still never leak raw at default, even with no specific copy
    # authored for it yet.
    copy = audit_events._describe_failure("some-new-refusal-nobody-mapped-yet")
    for key in ("headline", "meaning", "next_step"):
        assert "some-new-refusal-nobody-mapped-yet" not in copy[key]


def test_resolve_outcome_state_fails_safe_outside_the_known_vocabulary():
    # Defensive only: build_outcome is never called on an excluded row in
    # the real pipeline (list_audit_events drops those before reaching it),
    # but the function itself must not invent an in-flight/succeeded claim
    # for an action it does not recognise.
    assert audit_events.resolve_outcome_state("some-unknown-action", "whatever") == "failed"
